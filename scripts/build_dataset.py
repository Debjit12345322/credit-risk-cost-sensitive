"""
Build the labelled modelling dataset from the raw Kaggle file.

    python scripts/build_dataset.py

Reads   data/accepted_2007_to_2018Q4.csv.gz   (raw, 2.26M loans)
Writes  data/loans_2014.parquet               (labelled 2014 vintage)
        reports/target_audit.json             (row counts at every stage)
        reports/vintage_censoring.md          (why 2014: censoring by year)

Run once. Every later step reads the parquet, never the raw file: it loads in
about a second, preserves dtypes, and guarantees every analysis starts from the
same rows.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config import DATASET_FILE, RAW_FILE, REPORTS_DIR, TARGET_AUDIT_FILE, VINTAGE_YEAR
from src.data_loading import censoring_table, load_vintage
from src.reporting import md_table


def main() -> None:
    if not RAW_FILE.exists():
        sys.exit(
            f"Missing {RAW_FILE}.\nDownload it first:  make download   "
            f"(or see README > Reproducing)"
        )

    df, audit = load_vintage(RAW_FILE, year=VINTAGE_YEAR)

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    TARGET_AUDIT_FILE.write_text(json.dumps(audit, indent=2, default=str))
    df.to_parquet(DATASET_FILE, index=False)

    table = censoring_table(audit["census"])
    lines = [
        "# Vintage selection: censoring by origination year",
        "",
        "Generated by `scripts/build_dataset.py` from a full pass over the raw file.",
        "",
        "`unresolved` = Current, Late or In Grace Period at snapshot: no observed outcome.",
        "`resolved_default_share` = charged-off share among RESOLVED loans only. Its rise",
        "with recency is mostly censoring, not worsening credit: defaults resolve fast,",
        "healthy loans stay Current until their final payment, so dropping unresolved",
        "loans removes disproportionately good ones.",
        "",
        "The trend reverses in 2018: a loan must be 120+ days delinquent before it is",
        "charged off, so in the youngest vintage most defaults have not resolved yet,",
        "while prepayments can resolve in month one. At extreme censoring the resolved",
        "subset is dominated by early payoffs instead.",
        "",
        "2007-2010 also contain 'Does not meet the credit policy' statuses -- loans issued",
        "under an older underwriting regime -- which are excluded from both columns.",
        "",
        md_table(
            table.assign(year=table["year"].astype(int)),
            {"loans": ",d", "unresolved": ",d", "pct_unresolved": ".1f",
             "resolved_default_share": ".1f"},
        ),
        "",
    ]
    (REPORTS_DIR / "vintage_censoring.md").write_text("\n".join(lines))

    print(f"source rows      {audit['source_rows']:,}")
    print(f"{VINTAGE_YEAR} vintage     {audit['vintage_rows']:,}")
    print(f"dropped (no outcome) {audit['dropped_unresolved']:,}")
    print(f"unknown status   {audit['dropped_unknown_status']:,}")
    print(f"final            {audit['final_rows']:,} loans | default rate {audit['default_rate']:.4f}")


if __name__ == "__main__":
    main()
