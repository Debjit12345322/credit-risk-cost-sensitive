"""
Generate the leakage audit report and measure what the audit is worth.

    python scripts/run_leakage_audit.py

Writes  reports/leakage_audit.md   all 152 columns, bucket, fill rate, rationale
        reports/leakage_demo.md    same model with and without leaky columns

The demo trains the IDENTICAL LightGBM pipeline twice on the identical split:
once on the audited features (this is exactly the project's real baseline), once
with the post-origination columns added back. The gap is the cost of skipping
the audit, stated as a number rather than an assertion.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd
from sklearn.metrics import roc_auc_score

from src.config import DATASET_FILE, REPORTS_DIR, SEED
from src.leakage_audit import audit_columns, get_feature_columns, get_leak_columns
from src.pipeline import build_feature_frame, build_lgbm_model, split_indices, to_lgbm_frame
from src.reporting import md_table

BUCKET_ORDER = ["TARGET", "LEAK_PAYMENT", "LEAK_MONITORING", "LEAK_OUTCOME",
                "EMPTY_OR_CONST", "IDENTIFIER", "ANALYSIS_ONLY", "KEEP"]


def write_audit_report(df: pd.DataFrame) -> pd.DataFrame:
    audit = audit_columns(df)
    counts = audit["bucket"].value_counts()
    lines = [
        "# Leakage audit", "",
        "Generated by `scripts/run_leakage_audit.py` from `src/leakage_audit.py`.", "",
        "Test applied to every column: *would this value exist, with this value, in the",
        "lender's system at the moment the fund/decline decision is made?*", "",
        "`audit_columns()` raises on any unclassified column, so a schema change fails",
        "loudly instead of silently admitting an unvetted field.", "",
        "## Summary", "",
        md_table(pd.DataFrame({"bucket": [f"`{b}`" for b in BUCKET_ORDER if b in counts],
                               "columns": [int(counts[b]) for b in BUCKET_ORDER if b in counts]})),
        "", f"Total: **{len(audit)}** columns.", "",
    ]
    for b in BUCKET_ORDER:
        sub = audit[audit["bucket"] == b]
        if sub.empty:
            continue
        lines += [f"## {b}", "",
                  md_table(sub.assign(column=sub["column"].map(lambda c: f"`{c}`"))
                           [["column", "fill_rate", "rationale"]], {"fill_rate": ".1f"}), ""]
    (REPORTS_DIR / "leakage_audit.md").write_text("\n".join(lines))
    return audit


def run_demo(df: pd.DataFrame) -> list[tuple]:
    y = df["target"]
    X, numeric, categorical = build_feature_frame(df)
    X_clean = to_lgbm_frame(X, categorical)

    # Leak columns that are numeric can be appended directly. Categorical leak
    # columns (e.g. debt_settlement_flag) are left out -- the numeric ones are
    # already more than enough to show the effect.
    leaks = [c for c in get_leak_columns(df) if pd.api.types.is_numeric_dtype(df[c])]
    X_naive = pd.concat([X_clean, df[leaks]], axis=1)

    train_idx, test_idx = split_indices(y, SEED)
    results = []
    for name, frame in [("Naive (leaky columns added)", X_naive), ("Audited", X_clean)]:
        model = build_lgbm_model(SEED).fit(frame.iloc[train_idx], y.iloc[train_idx])
        auc = roc_auc_score(y.iloc[test_idx], model.predict_proba(frame.iloc[test_idx])[:, 1])
        top = (pd.Series(model.booster_.feature_importance("gain"), index=frame.columns)
               .sort_values(ascending=False).head(6).index.tolist())
        results.append((name, frame.shape[1], auc, top))
    return results


def leak_signatures(df: pd.DataFrame) -> tuple[pd.DataFrame, list[str]]:
    """The two clearest single-column illustrations of leakage."""
    fico = pd.DataFrame({
        "column": ["`fico_range_low` (at application)", "`last_fico_range_low` (re-pulled after origination)"],
        "mean_if_repaid": [df.loc[df.target == 0, "fico_range_low"].mean(),
                           df.loc[df.target == 0, "last_fico_range_low"].mean()],
        "mean_if_defaulted": [df.loc[df.target == 1, "fico_range_low"].mean(),
                              df.loc[df.target == 1, "last_fico_range_low"].mean()],
    })
    fico["gap"] = fico["mean_if_repaid"] - fico["mean_if_defaulted"]

    settled = df["debt_settlement_flag"].astype("string").str.strip() == "Y"
    recovered = df["recoveries"] > 0
    facts = [
        f"`debt_settlement_flag == 'Y'`: {int(settled.sum()):,} loans, default rate "
        f"{df.loc[settled, 'target'].mean():.1%}. A settlement only exists for a loan that already went bad.",
        f"`recoveries > 0`: {int(recovered.sum()):,} loans, default rate "
        f"{df.loc[recovered, 'target'].mean():.1%}. Recoveries are post-charge-off collections.",
    ]
    return fico, facts


def main() -> None:
    df = pd.read_parquet(DATASET_FILE)
    audit = write_audit_report(df)
    results = run_demo(df)
    fico, facts = leak_signatures(df)

    lines = [
        "# What the leakage audit is worth", "",
        f"Identical LightGBM pipeline, identical split (seed {SEED}), two feature sets. The",
        "audited row is the project's actual baseline model.", "",
        md_table(pd.DataFrame([(n, k, a) for n, k, a, _ in results],
                              columns=["feature set", "features", "test AUC"]),
                 {"test AUC": ".5f"}), "",
        "Top drivers of the naive model (by gain): "
        + ", ".join(f"`{c}`" for c in results[0][3]) + ".", "",
        "These are servicing fields that do not exist at decision time. An AUC near 1.0",
        "on consumer credit default is not a strong model; it is the signature of a leak.", "",
        "## The same quantity, measured before and after the outcome", "",
        md_table(fico, {"mean_if_repaid": ".1f", "mean_if_defaulted": ".1f", "gap": ".1f"}), "",
        "## Columns that are the label in disguise", "",
        *[f"- {f}" for f in facts], "",
    ]
    (REPORTS_DIR / "leakage_demo.md").write_text("\n".join(lines))

    kept = len(get_feature_columns(df))
    print(f"columns {len(audit)} | KEEP {kept} | not modelled {len(audit) - kept - 2} | target cols 2")
    for name, k, auc, _ in results:
        print(f"{name:<30} features={k:<4} AUC={auc:.5f}")


if __name__ == "__main__":
    main()
